/**
 * Find matched preset or build curriculum-specific factual data
 */
export function getAlgerianKnowledge(topic: string): KnowledgeTopicPreset | null {
  if (!topic || topic.trim().length === 0) return null;
  const clean = topic.trim().toLowerCase();

  // Exact or keyword match
  for (const preset of ALGERIAN_KNOWLEDGE_TOPICS) {
    if (preset.canonicalTitle.toLowerCase().includes(clean) || clean.includes(preset.id)) {
      return preset;
    }
    for (const kw of preset.keywords) {
      if (clean.includes(kw.toLowerCase())) {
        return preset;
      }
    }
  }

  return null;
}

