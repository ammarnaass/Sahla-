/**
 * Service Code to Icon Mapping Helper
 */
export function getServiceIcon(code: string, size: number | string = 24, className = "text-emerald-600 dark:text-emerald-400") {
  switch (code) {
    case "CV_GEN":
      return <DocCvIcon size={size} className={className} />;
    case "ID_PHOTO":
      return <CameraPhotoIcon size={size} className={className} />;
    case "INVOICE":
      return <InvoiceBillIcon size={size} className={className} />;
    case "SCHOOL_RESEARCH":
      return <SchoolCapIcon size={size} className={className} />;
    case "FORM_OCR":
      return <FormOcrIcon size={size} className={className} />;
    case "TAX_G50":
      return <TaxGovIcon size={size} className={className} />;
    case "CUSTOMERS":
      return <CustomersIcon size={size} className={className} />;
    case "EPAY":
      return <CardEpayIcon size={size} className={className} />;
    case "PRINT_BRIDGE":
      return <WirelessPrintIcon size={size} className={className} />;
    case "BARCODE":
      return <BarcodeQrIcon size={size} className={className} />;
    case "PDF_TOOLS":
      return <PdfToolsIcon size={size} className={className} />;
    default:
      return <DocCvIcon size={size} className={className} />;
  }
}
